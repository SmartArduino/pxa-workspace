"""Bake the editable artwork into shared PXA INDEX8 and RGB565 tables."""

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent
LIGHT = (1.0, 0.44, 0.54, 0.64, 0.74, 0.84, 0.94, 1.04)
# 0 is reserved for transparent grille and effect texels.
SPECIAL = [(52, 49, 52), (123, 89, 57), (202, 158, 96)]
SPECIAL += [(29, 66, 91), (37, 90, 114), (48, 118, 146), (57, 146, 173),
            (75, 182, 202), (110, 214, 224), (157, 234, 237), (206, 246, 236),
            (247, 251, 228)]


def concatenate(textures):
    strip = Image.new("RGB", (max(image.width for image in textures),
                              sum(image.height for image in textures)))
    start = 0
    for image in textures:
        strip.paste(image, (0, start))
        start += image.height
    return strip


def quantize(image, palette, offset, dither):
    indexed = image.quantize(palette=palette, dither=dither)
    return bytes(value + offset for value in indexed.tobytes())


def array(name, data):
    lines = [f"inline constexpr unsigned char {name}[] ="]
    for i in range(0, len(data), 24):
        values = "".join(f"\\x{byte:02x}" for byte in data[i:i + 24])
        lines.append(f'    "{values}"')
    return "\n".join(lines) + ";\n"


def rgb565(color, light):
    channels = [min(255, round(component * light)) for component in color]
    r, g, b = channels
    return (r >> 3) << 11 | (g >> 2) << 5 | b >> 3


def main():
    with Image.open(ROOT / "material-atlas.png") as atlas:
        width, height = atlas.size
        assert width == height and width % 2 == 0
        half = width // 2
        # Inset by two authoring pixels to avoid importing a neighboring tile.
        tiles = [atlas.crop((x * half + 2, y * half + 2,
                             (x + 1) * half - 2, (y + 1) * half - 2))
                 .convert("RGB").resize((size, size), Image.Resampling.LANCZOS)
                 for x, y, size in ((0, 0, 64), (1, 0, 64), (0, 1, 64), (1, 1, 128))]
    with Image.open(ROOT / "twilight.png") as backdrop:
        sky = backdrop.convert("RGB").crop((0, backdrop.height // 4,
                                           backdrop.width, backdrop.height))
        # Keep the sky's full projected horizontal detail by using two textures.
        sky = sky.resize((512, 128), Image.Resampling.LANCZOS)
    skyline = [sky.crop((x, 0, x + 256, 128)) for x in (0, 256)]

    colors = [(0, 0, 0)]
    baked = []
    groups = [
        (["twilight_left", "twilight_right"], skyline, 112),
        (["slate", "brass", "enamel", "moonstone"], tiles, 131),
    ]
    for names, images, count in groups:
        palette = concatenate(images).quantize(colors=count, method=Image.Quantize.MEDIANCUT)
        start = len(colors)
        raw = palette.getpalette()[:3 * count]
        assert len(raw) == 3 * count
        colors.extend(zip(raw[::3], raw[1::3], raw[2::3]))
        if names[0].startswith("twilight"):
            # Quantize continuously across the split. The distant skyline uses
            # a dedicated palette to keep flat gradients clear during motion.
            full_sky = quantize(sky, palette, start, Image.Dither.NONE)
            color_planes = [b"".join(full_sky[y * 512 + x:y * 512 + x + 256]
                                     for y in range(128)) for x in (0, 256)]
        else:
            color_planes = [quantize(image, palette, start, Image.Dither.FLOYDSTEINBERG)
                            for image in images]
        for name, indices in zip(names, color_planes):
            assert all(start <= index < start + count for index in indices)
            baked.append(array(name, indices))
    colors.extend(SPECIAL)
    assert len(colors) == 256

    values = [rgb565(color, shade) for shade in LIGHT for color in colors]
    palette_rows = ["    " + ", ".join(f"0x{value:04x}" for value in values[i:i + 12]) + ","
                    for i in range(0, len(values), 12)]
    header = ("// Generated by art/bake_textures.py.\n"
              "#pragma once\n\n#include <cstdint>\n\nnamespace raster_demo::baked {\n"
              f"inline constexpr std::uint8_t light_levels = {len(LIGHT)};\n"
              f"inline constexpr std::uint16_t palette[{len(values)}] = {{\n"
              + "\n".join(palette_rows) + "\n};\n\n" + "\n".join(baked)
              + "\n}  // namespace raster_demo::baked\n")
    (ROOT / "baked_textures.hpp").write_text(header, encoding="utf-8")


if __name__ == "__main__":
    main()
