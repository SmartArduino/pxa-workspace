esp_err_t espp4_a_panel_create(esp_lcd_panel_handle_t *panel)
{
    // Both display and touch are in one TDDI. Never pulse touch reset after
    // display initialization, including when constructing the touch driver.
    gpio_config_t pins = {.pin_bit_mask = (1ULL << 46) | (1ULL << 47),
        .mode = GPIO_MODE_OUTPUT};
    ESP_RETURN_ON_ERROR(gpio_config(&pins), "espp4_panel", "reset GPIO");
    ESP_RETURN_ON_ERROR(gpio_set_level(47, 1), "espp4_panel", "touch reset");
    gpio_set_level(46, 1); vTaskDelay(pdMS_TO_TICKS(100));
    gpio_set_level(46, 0); vTaskDelay(pdMS_TO_TICKS(100));
    gpio_set_level(46, 1); vTaskDelay(pdMS_TO_TICKS(120));
    static esp_ldo_channel_handle_t ldo;
    const esp_ldo_channel_config_t power = {.chan_id = 3, .voltage_mv = 2500};
    ESP_RETURN_ON_ERROR(esp_ldo_acquire_channel(&power, &ldo), "espp4_panel", "DSI power");
    const esp_lcd_dsi_bus_config_t bus_config = {.bus_id = 0,
        .num_data_lanes = 2, .lane_bit_rate_mbps = 440};
    esp_lcd_dsi_bus_handle_t bus;
    ESP_RETURN_ON_ERROR(esp_lcd_new_dsi_bus(&bus_config, &bus), "espp4_panel", "DSI bus");
    const esp_lcd_dbi_io_config_t command_config = {.virtual_channel = 0,
        .lcd_cmd_bits = 8, .lcd_param_bits = 8};
    esp_lcd_panel_io_handle_t io;
    ESP_RETURN_ON_ERROR(esp_lcd_new_panel_io_dbi(bus, &command_config, &io), "espp4_panel", "DBI");
    for (unsigned i = 0; i < sizeof(init_cmds) / sizeof(init_cmds[0]); ++i) {
        ESP_RETURN_ON_ERROR(esp_lcd_panel_io_tx_param(io, init_cmds[i].cmd,
            init_cmds[i].data, init_cmds[i].len), "espp4_panel", "ST7102 command");
        if (init_cmds[i].delay_ms) vTaskDelay(pdMS_TO_TICKS(init_cmds[i].delay_ms));
    }
    const esp_lcd_dpi_panel_config_t dpi = {
        .virtual_channel = 0, .dpi_clk_src = MIPI_DSI_DPI_CLK_SRC_DEFAULT,
        .dpi_clock_freq_mhz = 36, .in_color_format = LCD_COLOR_FMT_RGB565,
        .out_color_format = LCD_COLOR_FMT_RGB565, .num_fbs = 2,
        .video_timing = {.h_size = 480, .v_size = 854,
            .hsync_pulse_width = 5, .hsync_back_porch = 20, .hsync_front_porch = 60,
            .vsync_pulse_width = 5, .vsync_back_porch = 6, .vsync_front_porch = 195},
    };
    return esp_lcd_new_panel_dpi(bus, &dpi, panel);
}
